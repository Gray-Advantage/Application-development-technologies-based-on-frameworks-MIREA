"""
В таблице `ice_cream`

- сорта мороженого, которые должны быть видны на сайте (опубликованы),
  обозначаются значением `1` в поле `is_published` (в этом поле Python
  интерпретирует значение `1` как `True`);
- сорта мороженого, которые должны быть выведены на главную страницу проекта,
  обозначаются значением `1` в поле `is_on_main` (в этом поле Python
  интерпретирует значение `1` как `True`).

Напишите запрос, который сосчитает суммарную стоимость **опубликованных на
главной странице** сортов мороженого — тех, у каких одновременно есть статусы
«**опубликовано»** и **«показать на главной»**. Результат выведите в консоль.
"""

import sqlite3

con = sqlite3.connect("db.sqlite")
cur = con.cursor()

# Напишите SQL запрос в строке.
results = cur.execute("""
SELECT SUM(price)
FROM ice_cream
WHERE is_published = 1 AND is_on_main = 1;
""")


for result in results:
    print(result)

con.close()
