"""
Продолжим работать с той же базой.

Получите из базы данных информацию **о самом дешёвом мороженом** в каждой
**категории**.

Напомним структуру данных:

- ice_cream — сорта мороженого;

  Поля

  - id
  - title
  - description
  - price
  - category_id
  - wrapper_id

- categories — категории мороженого;

  Поля:

  - id
  - slug

- wrappers — перечень упаковок.

  Поля:

  - id
  - title

Для каждой категории выведите в консоль:

- **название** самого дешёвого мороженого в категории (поле `title` из таблицы
  **ice_cream**);
- **слаг категории**, которой принадлежит это мороженое (поле `slug` из таблицы
  **categories**);
- **название обёртки** этого мороженого (поле `title` из таблицы **wrappers**);
- **стоимость** этого мороженого (поле `price` из таблицы **ice_cream**). Чтобы
  найти минимальное значение, используйте оператор MIN;
- среднюю цену мороженого в категории.

Вывод в консоль должен выглядеть так:

```bash
# В БД есть две категории — значит, должно получиться две строки.
('название_самого_дешёвого_мороженого_в_категории_1', 'slug_категории_1',
'название_упаковки', <стоимость>, <средняя_стоимость_в_категории_1>)
('название_самого_дешёвого_мороженого_в_категории_2', 'slug_категории_2',
'название_упаковки', <стоимость>, <средняя_стоимость_в_категории_2>)
```
"""

import sqlite3

con = sqlite3.connect("db.sqlite")
cur = con.cursor()

# Вместо многоточия напишите запрос, который вернёт нужные данные:
results = cur.execute("""
SELECT ice_cream.title,
       categories.slug,
       wrappers.title,
       MIN(ice_cream.price),
       AVG(ice_cream.price)
FROM ice_cream
LEFT JOIN wrappers ON ice_cream.wrapper_id = wrappers.id
JOIN categories ON ice_cream.category_id = categories.id
GROUP BY categories.id
;
""")

for result in results:
    print(result)

con.close()
