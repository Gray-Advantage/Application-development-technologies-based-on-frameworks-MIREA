"""
В практических заданиях в тренажёре вам предстоит писать и развивать
Flask-приложение RandomStory. Это сервис, который даёт пользователям
возможность публиковать и читать короткие рассказы.

Допишите файл с приложением на Flask: напишите три view-функции для
маршрутизации запросов, каждая из которых будет обрабатывать запросы к
определённому URL. Проект должен содержать три страницы:

- `/`  — главная страница. В дальнейшем сюда будут выведены все рассказы,
  которые есть в проекте, а пока что выведите на неё текст `Это главная
  страница!`.
- `/add` — страница, на которой пользователь сможет опубликовать свой рассказ.
  Выведите на неё текст `Это страница для добавления рассказа`.
- `/story` — страница, куда впоследствии будет выводиться случайно выбранный
  рассказ. Выведите на неё текст `Это страница со случайным рассказом`.
"""

from flask import Flask

app = Flask(__name__)


@app.route("/")
def index_view() -> str:
    return "Это главная страница!"


@app.route("/add")
def add_view() -> str:
    return "Это страница для добавления рассказа"


@app.route("/story")
def random_story_view() -> str:
    return "Это страница со случайным рассказом"
