"""Исправьте функцию find_max_even_number() и добавьте аннотации типов.

Функция принимает список положительных целых чисел и возвращает
максимальное чётное число. Исправьте ошибку поиска минимума вместо
максимума, дайте параметру и переменным понятные имена, удалите
неиспользуемый импорт floor. Добавьте аннотации параметра и результата,
соблюдайте PEP 8: отступы, кавычки, длина строк и оформление docstring.
Сохраните начальное значение результата 0 для случая без чётных чисел.
Проверьте функцию несколькими вызовами, включая исходные примеры
[1, 2, 3, 4, 5], [10, 8, 6, 4, 2] и [2, 12, 85, 0, 6].
Для первого примера напечатайте «Максимальное чётное число: 4».
"""


def find_max_even_number(numbers: list[int]) -> int:
    """Вернуть максимальное чётное число или 0, если чётных чисел нет."""
    current_max = 0
    for number in numbers:
        if number % 2 == 0:
            current_max = max(number, current_max)
    return current_max


max_even = find_max_even_number([1, 2, 3, 4, 5])
print(f"Максимальное чётное число: {max_even}")

assert find_max_even_number([10, 8, 6, 4, 2]) == 10
assert find_max_even_number([2, 12, 85, 0, 6]) == 12
assert find_max_even_number([1, 3, 5]) == 0
assert find_max_even_number([]) == 0
