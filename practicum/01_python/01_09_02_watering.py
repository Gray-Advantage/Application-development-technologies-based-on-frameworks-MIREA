"""Правильный полив — ключ к здоровью растений!

Разные виды овощей требуют разного количества воды, и поливать огород надо
по науке.

Известно, сколько воды требуется для одного растения каждого вида, — и
теперь нужна программа, которая рассчитает общее количество воды,
необходимое для полива нескольких растений.

Например, на один куст огурцов нужно 3 литра воды. На огороде — 20 таких
кустов. Программа должна провести вычисления: `3 * 20` — и напечатать
понятно оформленный ответ.

Напишите функцию `calculate_watering()`, которая принимает три параметра:

1. `plant_type`: название растения (например, «Помидоры» или «Ананасы»).
2. `number_of_plants`: общее количество растений.
3. `volume_per_plant`: количество воды в литрах, необходимое для одного
растения. Это необязательный параметр. Значение этого параметра по умолчанию
должно быть 2.5 (такого объёма воды в среднем должно хватить любому
растению).

Функция `calculate_watering()` должна вычислить общее количество воды,
необходимое для полива, и **напечатать** строку:

```
<название_растения> <количество_растений> шт.: для полива требуется
<количество_воды> л воды.
```

Например:

```python
# При таком вызове:
calculate_watering('Огурцы', 20, 3)

# ...функция calculate_watering() должна напечатать строку
# Огурцы 20 шт.: для полива требуется 60 л воды.
```

Функция `calculate_watering()` не должна возвращать никаких значений.
"""


# Опишите параметры функции calculate_watering().
def calculate_watering(
    plant_type: str,
    number_of_plants: int,
    volume_per_plant: float = 2.5,
) -> None:
    total_volume = number_of_plants * volume_per_plant
    print(
        f"{plant_type} {number_of_plants} шт.: "
        f"для полива требуется {total_volume} л воды."
    )


# Не изменяйте код ниже этого комментария:
# если ваша функция написана правильно - эти вызовы должны успешно сработать.

# Вызов функции с позиционными аргументами:
calculate_watering("Артишоки", 20, 4)

# Вызов функции с позиционными аргументами, без опционального:
calculate_watering("Кивано", 15)

# Вызов функции с именованными аргументами, без опционального:
calculate_watering(number_of_plants=15, plant_type="Тыквы")
