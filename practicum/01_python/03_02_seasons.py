"""Ветвления — определение времени года.

Функция get_season принимает русское название месяца в нижнем регистре
и возвращает название сезона. Любое другое слово или неверный регистр
должны дать строку «Ошибка в написании месяца!».
Используйте конструкцию if/elif/else для всех двенадцати месяцев.
"""


def get_season(month_name):
    if month_name in ("декабрь", "январь", "февраль"):
        return "зима"
    elif month_name in ("март", "апрель", "май"):
        return "весна"
    elif month_name in ("июнь", "июль", "август"):
        return "лето"
    elif month_name in ("сентябрь", "октябрь", "ноябрь"):
        return "осень"
    else:
        return "Ошибка в написании месяца!"


print(get_season("июнь"))
print(get_season("мартобрь"))
