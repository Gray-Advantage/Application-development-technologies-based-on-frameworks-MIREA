"""Логические операторы — четверть координатной плоскости.

Для заданных x и y напечатайте четверть точки. При нуле хотя бы одной
координаты сообщите, что точка на оси и не принадлежит ни одной четверти.
Сохраните сообщения и порядок ветвей исходного шаблона.
"""

x = -2
y = 5

if x == 0 or y == 0:
    print("Точка лежит на оси координат и не принадлежит ни одной четверти")
elif x > 0 and y > 0:
    print("Первая четверть")
elif x > 0 and y < 0:
    print("Четвертая четверть")
elif x < 0 and y > 0:
    print("Вторая четверть")
else:
    print("Третья четверть")
