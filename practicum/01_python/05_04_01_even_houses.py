"""Создайте диапазон номеров первых семи домов на чётной стороне улицы.

Заданы houses_count = 7, step = 2 и start = 2. Вычислите правую границу
end и создайте range houses, содержащий номера от первого дома до
седьмого включительно: 2, 4, 6, 8, 10, 12, 14. Сохраните готовый вывод
«Номера домов по чётной стороне:» и преобразование диапазона в список.
"""

houses_count = 7
step = 2
start = 2
end = start + houses_count * step
houses = range(start, end, step)
print("Номера домов по чётной стороне:", list(houses))
