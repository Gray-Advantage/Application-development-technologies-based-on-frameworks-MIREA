"""Для решения этой задачи вам нужно узнать кое-что новое. Методы класса можно
использовать как «альтернативные конструкторы»: с их помощью удобно
создавать новые экземпляры класса с разным набором исходных данных.

Например, у встроенного класса `date` есть класс-метод `date.today()`,
который создаёт объект текущей даты — и при этом вам не нужно явно
передавать в конструктор год, месяц и день.

А теперь — задача.

При регистрации в социальной сети пользователю дана возможность указать или
имя с фамилией (например, `Стас Басов`), или псевдоним — абстрактное имя
пользователя (например, `nestas_anonymous`).

В прекоде создан класс `User` — он отвечает за управление пользователями.

В классе есть атрибуты

- `first_name` — имя пользователя,
- `last_name` — фамилия пользователя,
- `username` — псевдоним пользователя.

По соображениям безопасности псевдоним пользователя не должен начинаться со
слова `'admin'`.

В классе `User` объявлены

- пустой **метод класса** `with_name()`. Напомним, что пустые методы ничего
не делают — только принимают параметры и возвращают результат:
    - должен принимать на вход имя и фамилию пользователя,
    - должен возвращать объект класса `User` с заполненными атрибутами
    `first_name` и `last_name`. Подсказка: для этого достаточно создать
    новый объект (`User(…)`) с нужными параметрами.
- пустой **метод класса** `with_username()` — возвращает объект класса
`User`:
    - должен принимать на вход псевдоним пользователя;
    - при помощи статического метода `is_username_allowed()` метод
    `with_username()` должен проверять, разрешено ли использование
    полученного псевдонима. Если псевдоним некорректный — метод
    `with_username()` должен выбрасывать исключение `ValueError` с
    сообщением `Некорректное имя пользователя`; пример того, как
    выбрасывается исключение, можно подсмотреть в методе `__init__()`.
    - должен возвращать объект класса `User` с заполненным атрибутом
    `username`;
- пустой **статический метод класса** `is_username_allowed()` — проверяет
псевдонимы на соответствие правилам:
    - должен принимать на вход значение атрибута `username`;
    - возвращать `True`, если `username` не начинается с подстроки
    `'admin'`;
- пустой **метод-свойство** `full_name()` — возвращает информацию о
пользователе:
    - если для объекта заданы значения атрибутов `first_name` и `last_name`,
    то метод должен вернуть имя пользователя в виде `first_name last_name`
    (например: `Стас Басов`);
    - если для объекта задано значение атрибута `username`, то метод должен
    вернуть имя пользователя в виде `@username` (например:
    `@nestas_anonymous`).

Допишите все методы и свойство класса `User`.

Для того, чтобы планомерно двигаться к решению, попробуйте решать по частям:
1. Сначала реализуйте альтернативный конструктор `with_name` для
пользователей с именем и фамилией.
2. Затем реализуйте статический метод `is_username_allowed` и на его основе
— альтернативный конструктор `with_username`.
3. В конце опишите свойство `full_name`, которое аккуратно показывает
пользователя либо по имени и фамилии, либо по псевдониму.
"""


class User:
    def __init__(
        self,
        first_name: str | None = None,
        last_name: str | None = None,
        username: str | None = None,
    ) -> None:
        if not first_name and not last_name and not username:
            raise ValueError("Необходимо указать параметры пользователя")

        self.first_name = first_name
        self.last_name = last_name
        self.username = username

    # Опишите метод класса with_name.
    @classmethod
    def with_name(cls, first_name: str, last_name: str) -> "User":
        return cls(first_name=first_name, last_name=last_name)

    # Опишите метод класса with_username.
    @classmethod
    def with_username(cls, username: str) -> "User":
        if not cls.is_username_allowed(username):
            raise ValueError("Некорректное имя пользователя")
        return cls(username=username)

    # Опишите статический метод класса is_username_allowed.
    @staticmethod
    def is_username_allowed(username: str) -> bool:
        return not username.startswith("admin")

    # Опишите метод-свойство full_name.
    @property
    def full_name(self) -> str:
        if self.first_name and self.last_name:
            return f"{self.first_name} {self.last_name}"
        return f"@{self.username}"


stas = User.with_name("Стас", "Басов")
print(stas.full_name)

