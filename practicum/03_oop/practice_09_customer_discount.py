"""Торговая сеть ООП заботится о своих посетителях и предоставляет им скидки.

В программе, которая управляет ценами на товары, надо реализовать механизм
вычисления цены с учётом скидки конкретного клиента.

В прекоде объявлен класс `Customer`, в нём есть только один атрибут — `name`,
он хранит имя пользователя.

Допишите класс `Customer`.

1. В инициализаторе класса `Customer` создайте **приватный** атрибут, который
   будет хранить значение скидки для конкретного клиента (в процентах).
   По-английски «скидка» — это *discount*, так этот атрибут и назовите. У этого
   атрибута должно быть значение по умолчанию: 10.

    Этот атрибут не должен быть доступен для изменений извне.

2. В этом же классе реализуйте метод `get_price()`. Этот метод должен
    - принять на вход исходную цену товара,
    - вычислить новую цену: к полученной цене применить скидку и округлить
      результат до двух знаков после запятой,
    - вернуть новую цену.
3. Реализуйте метод `set_discount()`, который принимает на вход новое значение
   скидки и заменяет значение соответствующего атрибута.

    Магазин не может предоставить скидку более 80%. В методе `set_discount()`
    реализуйте проверку: если этот метод получит на вход значение **более 80**
    — должно быть сохранено значение 80.
"""


class Customer:
    def __init__(self, name: str):
        self.name = name
        self.__discount = 10

    def set_discount(self, new_value: int):
        self.__discount = min(new_value, 80)

    def get_price(self, price: int) -> float:
        return round(price * (100 - self.__discount) / 100, 2)


# Проверим работу программы.
# Создаём объект покупателя:
customer = Customer("Иван Иванович")

original_price = 85

print(
    f"С исходной скидкой Иван Иванович заплатит "
    f"{customer.get_price(original_price)} рублей вместо {original_price}"
)
# Изменим скидку до неприемлемого уровня.
# Метод set_discount() должен установить размер скидки равным 80.
customer.set_discount(90)
print(
    f"С новой скидкой Иван Иванович заплатит "
    f"{customer.get_price(original_price)} рублей вместо {original_price}"
)
