"""Разработчик начал писать приложение для грибников, но наступила зима — и ему
стало не до грибов. Вам предстоит закончить работу над приложением.

Идея приложения такова: создаётся программная «корзина для грибов» (**объект**
класса `MushroomsCollector`), и каждый найденный в лесу гриб добавляется в эту
корзину (учитывается в программе). Если гриб несъедобен — программа должна
запретить добавление этого гриба в корзину.

Может быть создано несколько таких «программных корзин».

В прекоде есть класс `MushroomsCollector`, он отвечает за проверку и сохранение
грибов. Допишите этот класс и исправьте ошибки.

- Сейчас `mushrooms` объявлен как атрибут класса, поэтому все корзины делят
  один общий список. Исправьте код так, чтобы каждая корзина хранила
  собственный список грибов.
- Метод `is_poisonous()` должен принять на вход название гриба и проверить, не
  ядовит ли гриб.  Сейчас этот метод работает с ошибкой и признаёт все грибы
  ядовитыми. Исправьте этот метод так, чтобы он нормально выполнял свою задачу.
- Метод `add_mushroom()` должен принять на вход название гриба и, если гриб не
  ядовит (если метод `is_poisonous()` вернул `False`), сохранить его в список
  `mushrooms`.

    Если же метод `is_poisonous()` вернул `True` — программа должна напечатать
    сообщение об ошибке:

    ```
    Нельзя добавить ядовитый гриб
    ```

- Реализуйте магический метод `__str__`, который выводит через запятую и пробел
  элементы списка `mushrooms` конкретного объекта класса `MushroomsCollector`.
  Например:

    ```
    белый, рыжик, груздь, лисичка
    ```
"""


class MushroomsCollector:
    def __init__(self):
        self.mushrooms = []

    def is_poisonous(self, mushroom_name):
        return mushroom_name in ("Мухомор", "Поганка")

    def add_mushroom(self, mushroom_name):
        if self.is_poisonous(mushroom_name):
            print("Нельзя добавить ядовитый гриб")
        else:
            self.mushrooms.append(mushroom_name)

    def __str__(self):
        return ", ".join(self.mushrooms)


# Пример запуска для самопроверки
collector_1 = MushroomsCollector()
collector_1.add_mushroom("Мухомор")
collector_1.add_mushroom("Подосиновик")
collector_1.add_mushroom("Белый")
print(collector_1)

collector_2 = MushroomsCollector()
collector_2.add_mushroom("Лисичка")
print(collector_1)
print(collector_2)
