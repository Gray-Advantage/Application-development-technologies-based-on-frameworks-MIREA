"""В биологической лаборатории выводят премиальную породу очень полезных
бактерий. Отдельные колонии бактерий выращивают в автоматизированных чашках
Петри.

Но бактерии вырвались на свободу и устроили короткое замыкание. Система
управления сгорела, программа была уничтожена. Спасать ситуацию выпало именно
вам: надо восстановить программу.

## Как должна работать программа

При создании новой колонии в программе создаётся объект класса
`BacteriaProducer` и устанавливается предельная численность популяции: в
инициализатор класса передаётся параметр `max_bacteria`.

Текущее количество бактерий в колонии хранится в атрибуте объекта
`current_bacteria_count`.

Помимо инициализатора у экземпляров класса `BacteriaProducer` есть два метода:

- при вызове метода `delete()` должна удаляться одна бактерия из популяции:
  счётчик `current_bacteria_count` должен уменьшиться на 1;
- при вызове метода `create()` в популяцию должна добавляться одна бактерия:
  счётчик `current_bacteria_count` должен увеличиться на 1;

Значение счётчика `current_bacteria_count` не должно превышать значение
`max_bacteria` и не должно быть меньше 0.

1. В инициализаторе класса опишите два атрибута:
    - атрибут `max_bacteria` должен быть равен значению аргумента
      `max_bacteria`, переданного в инициализатор класса при создании объекта;
    - атрибут `current_bacteria_count` должен хранить количество бактерий в
      каждый текущий момент времени. По умолчанию этот атрибут должен быть
      равен 0.
2. Опишите метод `create()`, который отвечает за добавление бактерии в колонию.

    При вызове этого метода счётчик бактерий `current_bacteria_count` должен
    увеличиться на единицу.

    Если в момент вызова этого метода количество бактерий в популяции
    `current_bacteria_count` равно максимально возможному количеству бактерий в
    колонии `max_bacteria` — новую бактерию не следует добавлять; программа
    должна напечатать сообщение об ошибке:

    ```
    Нет места под новую бактерию
    ```

    В ином случае увеличьте счётчик бактерий на единицу и напечатайте
    сообщение:

    ```
    Добавлена одна бактерия. Бактерий в колонии: <число>
    ```

3. Опишите метод `delete()`, который при каждом вызове удаляет из колонии по
   одной бактерии.

    Если в момент вызова этого метода количество бактерий в популяции
    `current_bacteria_count` равно нулю — бактерию удалить невозможно.
    Программа должна напечатать сообщение об ошибке:

    ```
    В популяции нет бактерий, удалять нечего
    ```

    В ином случае уменьшите счётчик бактерий на единицу и напечатайте
    сообщение:

    ```
    Одна бактерия удалена. Бактерий в колонии: <число>
    ```
"""


class BacteriaProducer:
    def __init__(self, max_bacteria):
        self.max_bacteria = max_bacteria
        self.current_bacteria_count = 0

    def create(self):
        if self.current_bacteria_count >= self.max_bacteria:
            print("Нет места под новую бактерию")
        else:
            self.current_bacteria_count += 1
            print(
                "Добавлена одна бактерия. "
                f"Бактерий в колонии: {self.current_bacteria_count}"
            )

    def delete(self):
        if self.current_bacteria_count == 0:
            print("В популяции нет бактерий, удалять нечего")
        else:
            self.current_bacteria_count -= 1
            print(
                "Одна бактерия удалена. "
                f"Бактерий в колонии: {self.current_bacteria_count}"
            )


# Пример запуска для самопроверки
bacteria_producer = BacteriaProducer(max_bacteria=3)
bacteria_producer.delete()
bacteria_producer.create()
bacteria_producer.create()
bacteria_producer.create()
bacteria_producer.create()
bacteria_producer.delete()
