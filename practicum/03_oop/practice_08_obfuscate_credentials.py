"""При отладке социальной сети потребовалось напечатать конфиденциальные
данные: логин и пароль пользователя. Безопасности никогда не бывает слишком
много: вдруг шпион-злоумышленник следит за монитором разработчика? Данные лучше
выводить в скрытом, но узнаваемом виде.

Есть функция, которая возвращает словарь (dict) с ключами `name` и `password`.
Значения ключей — это строки.

**Напишите декоратор** `obfuscator()`, который будет скрывать значения по
такому правилу:

1. В строке, переданной под ключом `name`, каждый символ, кроме первого и
   последнего, должен быть заменён на звёздочки `*`. Первый и последний символы
   должны остаться, как были; общее количество символов должно совпадать с
   исходным.
2. В строке, переданной под ключом `password`, каждый символ должен быть
   заменён на звёздочку `*`. Количество звёздочек должно соответствовать
   количеству символов в исходном пароле.

Пример:

```python
# Исходная функция возвращает такой словарь:
{
    'name': 'Vasya',
    'password': '123456'
}

# Задекорированная функция должна вернуть такой словарь:
{
    'name': 'V***a',
    'password': '******'
}
```
"""


def obfuscator(func):
    def wrapper():
        credentials = func().copy()
        name = credentials["name"]
        if len(name) > 2:
            credentials["name"] = name[0] + "*" * (len(name) - 2) + name[-1]
        credentials["password"] = "*" * len(credentials["password"])
        return credentials

    return wrapper


@obfuscator
def get_credentials():
    return {
        "name": "StasBasov",
        "password": "iamthebest",
    }


print(get_credentials())
