"""Торговой сети «ООП» («**О**бъединяющий **О**птимальные **П**реимущества™»)
нужна программа для учёта товаров.

Все товары очень разные и с разными признаками: например, в спортивном отделе
продаются гири, у них есть признак «вес». У одежды нет признака «вес», зато
есть признак «размер».

Однако у любого товара обязательно есть параметры «название» и «количество на
складе».

Ваша задача — написать программу, в которой можно создавать объекты товаров
разного типа (с разными свойствами). У этих объектов должны быть методы,
которые вернут данные о товаре.

В программе должны быть описаны три класса:

1. Класс `Product` уже описан в коде. Этот класс описывает товар в общем виде.
   Инициализатор этого класса должен принимать на вход два параметра: название
   товара `name` и количество товара `quantity`. От класса `Product`
   наследуются классы конкретных товаров.

    В классе `Product` описаны два метода:

    - метод `get_basic_info()`, который возвращает строку в таком формате:

        ```bash
        <название товара> (в наличии: <количество_товара>)
        # Например:
        Сковорода (в наличии: 42)
        ```

    - пустой метод `get_full_info()`: этот метод надо будет переопределить в
      унаследованных классах.
2. Класс `Kettlebell` (наследуется от `Product`), описывающий спортивные гири.

    Инициализатор этого класса должен принимать, помимо параметров
    родительского класса, значение для параметра `weight` (вес гири в
    килограммах).

    Переопределите в классе `Kettlebell` метод `get_full_info()`. Этот метод
    должен вернуть строку с полным описанием товара.

    Возвращаемая строка должна быть составлена из

    - базового описания товара: это результат вызова `get_basic_info()`;
    - уникальной информации о товаре: это вес продукта `weight`.

    Общий вид строки, которую должен вернуть метод `get_full_info()`:

    ```bash
    <название товара> (в наличии: <количество_товара>). Вес: <число> кг
    # Например:
    Гиря детская (в наличии: 12). Вес: 0.75 кг
    ```


3. Класс `Clothing` (наследуется от `Product`), описывающий предметы одежды.

    Инициализатор этого класса должен принимать, помимо параметров
    родительского класса, значение для параметра `size` (размер одежды).

    Переопределите в классе `Clothing` метод `get_full_info()`. Этот метод
    должен вернуть строку с полным описанием товара.

    Возвращаемая строка должна быть составлена из

    - базового описания товара: это результат вызова `get_basic_info()`;
    - уникальной информации о товаре: это размер одежды `size`.

    Общий вид строки, которую должен вернуть метод `get_full_info()`:

    ```bash
    <название товара> (в наличии: <число>). Размер: <размер>
    # Например:
    Шляпа с рукавами (в наличии: 3). Размер: XXL
    ```
"""


class Product:
    def __init__(self, name, quantity):
        self.name = name
        self.quantity = quantity

    def get_basic_info(self):
        return f"{self.name} (в наличии: {self.quantity})"

    def get_full_info(self):
        pass


class Kettlebell(Product):
    def __init__(self, name, quantity, weight):
        super().__init__(name, quantity)
        self.weight = weight

    def get_full_info(self):
        return f"{self.get_basic_info()}. Вес: {self.weight} кг"


class Clothing(Product):
    def __init__(self, name, quantity, size):
        super().__init__(name, quantity)
        self.size = size

    def get_full_info(self):
        return f"{self.get_basic_info()}. Размер: {self.size}"


# Для проверки вашего кода создадим пару объектов...
small_kettlebell = Kettlebell("Гиря малая", 15, 2)
shirt = Clothing("Футболка", 5, "L")

# ...и вызовем их методы:
print(small_kettlebell.get_full_info())
print(shirt.get_full_info())
