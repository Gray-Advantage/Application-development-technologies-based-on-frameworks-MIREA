"""
Подготовка к конкурсу «Лучший рецепт мороженого друзей Анфисы» продолжается.
Заказчику показали форму подачи заявки, и по итогам презентации руководство
сообщило: «Отличная работа! Всё переделать!»

Оказалось, заказчик хочет видеть сообщение об успешной отправке на той же
странице, где размещена форма: тогда пользователь сразу сможет отправить ещё
одну заявку, а потом ещё одну и ещё!

Переделка проекта начата, вам нужно её завершить. Внесите изменения в файлы
*contest/views.py* и *templates/contest/form.html.* Остальные файлы изменять не
нужно — они уже исправлены.

Вместо двух прежних view-функций создана одна новая — `proposal()`; она
вызывается при обращении к адресу *contest/*.

Допишите эту view-функцию: она должна передавать в шаблон объект формы
`ContestForm`, а при успешной отправке формы выводить на страницу сообщение

```
Рецепт мороженого "<название_мороженого>" принят на конкурс!
```

`<название_мороженого>` в сообщении — это значение поля `title`. Сообщение
должно быть заключено в тег `<h2>`.

![](https://pictures.s3.yandex.net:443/resources/146_1682596102.png)
"""

from django.shortcuts import render

from .forms import ContestForm


def proposal(request):
    form = ContestForm(request.GET or None)
    return render(request, "contest/form.html", {"form": form})
